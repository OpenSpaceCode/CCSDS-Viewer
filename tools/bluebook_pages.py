#!/usr/bin/env python3
"""Generates src/lib/bluebook-pages.js: where each section, table, figure and annex of the Blue Books is.

The links open the PDFs on ccsds.org at these pages, so run this on the same files: compare their SHA-256 with the online ones.
Needs pypdf and the PDFs in pdf/ (not committed).

Usage: python3 tools/bluebook_pages.py [--check]    --check: fail if the committed table is out of date
"""
import hashlib, json, os, re, sys

import pypdf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, 'src', 'lib', 'bluebook-pages.js')
FILES = {'tm': '132x0b3_TM_SDLP.pdf', 'tc': '232x0b4e1c1_TC_SDLP.pdf', 'spp': 'space_packet_ccsds.pdf', 'sdls': '355x0b2-SDLS.pdf', 'ep': '355x1b1-sdls-ep.pdf'}

SECTION = re.compile(r'^(\d+(?:\.\d+)+)\s+\S')
CAPTION = re.compile(r'^(Table|Figure) ([A-Z]?\d*-\d+)\s*:')
ANNEX = re.compile(r'^ANNEX ([A-Z])\s*$')
PRINTED = re.compile(r'Page ([A-Za-z0-9-]+) ')


def first_body_page(pages):
    # The contents list the same numbers, so only look from where the text proper begins.
    for i, text in enumerate(pages):
        if re.search(r'^1 INTRODUCTION\s*$', text, re.M):
            return i
    raise SystemExit('no "1 INTRODUCTION" heading found')


def scan(path):
    with open(path, 'rb') as f:
        sha256 = hashlib.sha256(f.read()).hexdigest()
    pages = [p.extract_text() or '' for p in pypdf.PdfReader(path).pages]
    start = first_body_page(pages)
    out = {'sha256': sha256, 'pages': len(pages), 'printed': [], 'sections': {}, 'tables': {}, 'figures': {}, 'annexes': {}}
    for text in pages:
        m = PRINTED.search(text)
        out['printed'].append(m.group(1) if m else '')
    # The first time a number opens a line is its heading: conformance tables and indexes repeat them later on.
    for i in range(start, len(pages)):
        for line in pages[i].split('\n'):
            line = line.strip()
            if '....' in line:
                continue
            m = SECTION.match(line)
            if m:
                out['sections'].setdefault(m.group(1), i + 1)
            m = CAPTION.match(line)
            if m:
                out['tables' if m.group(1) == 'Table' else 'figures'].setdefault(m.group(2), i + 1)
            m = ANNEX.match(line)
            if m:
                out['annexes'].setdefault(m.group(1), i + 1)
    return out


def render():
    data = {doc: scan(os.path.join(ROOT, 'pdf', name)) for doc, name in FILES.items()}
    body = ',\n'.join('  %s: %s' % (doc, json.dumps(data[doc], separators=(',', ':'), ensure_ascii=False)) for doc in FILES)
    return '// GENERATED by tools/bluebook_pages.py from the Blue Book PDFs. Do not edit.\n// PDF page number of each section, table, figure and annex, and the page number printed on each PDF page.\nconst BLUE_BOOK_PAGES = {\n' + body + '\n};\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        with open(OUTPUT, encoding='utf-8') as f:
            if f.read() != text:
                raise SystemExit('src/lib/bluebook-pages.js is out of date: run python3 tools/bluebook_pages.py')
        print('src/lib/bluebook-pages.js is up to date')
    else:
        with open(OUTPUT, 'w', encoding='utf-8', newline='') as f:
            f.write(text)
        print('wrote src/lib/bluebook-pages.js (%d KB)' % (len(text) // 1024))
